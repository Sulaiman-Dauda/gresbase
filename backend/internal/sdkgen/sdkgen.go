// interfaceName converts a collection name into a PascalCase TypeScript
// interface identifier (e.g. "blog_posts" -> "BlogPosts").
func interfaceName(name string) string {
	parts := splitName(name)
	if len(parts) == 0 {
		return "Record_"
	}
	var b strings.Builder
	for _, p := range parts {
		b.WriteString(strings.ToUpper(p[:1]) + p[1:])
	}
	out := sanitizeIdent(b.String())
	if out == "" {
		return "Record_"
	}
	return out
}

// methodName converts a collection name into a camelCase property identifier
// used on the client (e.g. "blog_posts" -> "blogPosts").
func methodName(name string) string {
	parts := splitName(name)
	if len(parts) == 0 {
		return "collection_"
	}
	var b strings.Builder
	for i, p := range parts {
		if i == 0 {
			b.WriteString(strings.ToLower(p[:1]) + p[1:])
			continue
		}
		b.WriteString(strings.ToUpper(p[:1]) + p[1:])
	}
	out := sanitizeIdent(b.String())
	if out == "" {
		return "collection_"
	}
	// A leading digit is not a valid identifier start.
	if out[0] >= '0' && out[0] <= '9' {
		return "_" + out
	}
	return out
}

// splitName breaks a collection name on common word separators.
func splitName(name string) []string {
	fields := strings.FieldsFunc(name, func(r rune) bool {
		return r == '_' || r == '-' || r == ' ' || r == '.'
	})
	out := make([]string, 0, len(fields))
	for _, f := range fields {
		if f != "" {
			out = append(out, f)
		}
	}
	return out
}

// sanitizeIdent strips characters that are invalid in a TS identifier.
func sanitizeIdent(s string) string {
	var b strings.Builder
	for _, r := range s {
		if (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || (r >= '0' && r <= '9') || r == '_' {
			b.WriteRune(r)
		}
	}
	return b.String()
}

// encodeURIPath escapes a collection name for safe interpolation into a URL
// path segment within a backtick template literal.
func encodeURIPath(name string) string {
	var b strings.Builder
	for _, r := range name {
		if (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || (r >= '0' && r <= '9') ||
			r == '-' || r == '_' || r == '.' || r == '~' {
			b.WriteRune(r)
			continue
		}
		for _, by := range []byte(string(r)) {
			fmt.Fprintf(&b, "%%%02X", by)
		}
	}
	return b.String()
}

// tsStringLiteral renders a Go string as a double-quoted TypeScript literal.
func tsStringLiteral(s string) string {
	r := strings.NewReplacer(
		"\\", "\\\\",
		"\"", "\\\"",
		"\n", "\\n",
		"\r", "\\r",
		"\t", "\\t",
	)
	return "\"" + r.Replace(s) + "\""
}
